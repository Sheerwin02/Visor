"""Estimation-test stimuli and analysis (plan-view hillshade). Not the first-person visor view: say so in the write-up.
  python make_stimuli.py make   OUTDIR [--dem dem.npy --cell 1.0]   # images at low and high sun + answer key + response sheet
  python make_stimuli.py analyze OUTDIR responses.csv               # N, median absolute error and IQR by sun elevation
Task: for each numbered marker, estimate the ground slope in degrees. Same markers at LOW and HIGH sun; each participant sees the
items in their own random order and only ONE sun level per marker (assign by participant number parity) so nobody sees the same marker twice.
No significance test and no training claim are made: with 8-10 people report N, medians, spread and the raw points.
Default terrain is SYNTHETIC (synth_boxwork.py); with real data pass a 1 m DEM crop saved as .npy.
Fake responses used to test this code are generated by `selftest` and are NOT data."""
import os, sys, csv, argparse, numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import misleading_slope as ms
LOW, HIGH, AZ = 15.0, 55.0, 90.0   # sun elevations (assumed test values) and one east-sun azimuth

def hillshade_img(dem, cell, el, az):
    slope, da = ms.slope_aspect(dem, cell, smooth_m=0)
    sh = ms.shade(slope, da, el, az)
    return (np.clip(sh, 0, 1) * 255).astype(np.uint8), np.degrees(slope)

def pick_markers(slope_deg, n=8, seed=3, margin=10):
    rng = np.random.default_rng(seed)
    targets = np.linspace(5, 40, n)             # spread of true slopes to test
    pts, used = [], []
    for t in targets:
        cand = np.argwhere((np.abs(slope_deg - t) < 1.5))
        cand = cand[(cand[:, 0] > margin) & (cand[:, 1] > margin) & (cand[:, 0] < slope_deg.shape[0] - margin) & (cand[:, 1] < slope_deg.shape[1] - margin)]
        cand = [c for c in cand if all(np.hypot(*(c - u)) > 25 for u in used)]
        if cand:
            c = cand[rng.integers(len(cand))]; used.append(c); pts.append((int(c[0]), int(c[1]), float(slope_deg[c[0], c[1]])))
    return pts

def make(outdir, dem=None, cell=1.0):
    from PIL import Image, ImageDraw
    os.makedirs(outdir, exist_ok=True)
    if dem is None:
        import synth_boxwork as sb
        z, st = sb.make(relief=1.0); dem = sb.block_mean(z, int(1 / st)); cell = 1.0
    _, slope = hillshade_img(dem, cell, LOW, AZ)
    pts = pick_markers(slope)
    with open(os.path.join(outdir, "key.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["item", "row", "col", "true_slope_deg"])
        for i, (r, c, s) in enumerate(pts, 1): w.writerow([i, r, c, "%.1f" % s])
    for name, el in (("low", LOW), ("high", HIGH)):
        g, _ = hillshade_img(dem, cell, el, AZ)
        for i, (r, c, s) in enumerate(pts, 1):      # one crop per marker so each item is its own picture
            r0, c0 = max(r - 30, 0), max(c - 30, 0)
            crop = Image.fromarray(g[r0:r0 + 60, c0:c0 + 60]).resize((360, 360), Image.NEAREST).convert("RGB")
            d = ImageDraw.Draw(crop); cx, cy = (c - c0) * 6, (r - r0) * 6
            d.ellipse([cx - 9, cy - 9, cx + 9, cy + 9], outline=(255, 60, 60), width=2); d.text((cx + 12, cy - 6), str(i), fill=(255, 60, 60))
            crop.save(os.path.join(outdir, "item%02d_%s.png" % (i, name)))
    with open(os.path.join(outdir, "response_sheet.csv"), "w", newline="") as f:
        csv.writer(f).writerow(["participant", "item", "sun", "estimated_slope_deg"])
    print("wrote %d items x 2 sun levels to %s; sun low %.0f deg, high %.0f deg, az %.0f (ASSUMED test values)" % (len(pts), outdir, LOW, HIGH, AZ))

def analyze(outdir, resp):
    key = {int(r["item"]): float(r["true_slope_deg"]) for r in csv.DictReader(open(os.path.join(outdir, "key.csv")))}
    err = {"low": [], "high": []}; people = set()
    for r in csv.DictReader(open(resp)):
        people.add(r["participant"]); err[r["sun"]].append(abs(float(r["estimated_slope_deg"]) - key[int(r["item"])]))
    print("participants N =", len(people))
    for k, v in err.items():
        if v: q = np.percentile(v, [25, 50, 75]); print("%s sun: n=%d, median abs error %.1f deg, IQR %.1f to %.1f" % (k, len(v), q[1], q[0], q[2]))
    print("No significance claim. Report these numbers with N and the raw points.")

def selftest(tmp):
    make(tmp)
    rng = np.random.default_rng(0)
    key = list(csv.DictReader(open(os.path.join(tmp, "key.csv"))))
    with open(os.path.join(tmp, "FAKE_responses.csv"), "w", newline="") as f:
        w = csv.writer(f); w.writerow(["participant", "item", "sun", "estimated_slope_deg"])
        for p in range(1, 9):
            for k in key:
                sun = "low" if (p + int(k["item"])) % 2 else "high"
                w.writerow([p, k["item"], sun, float(k["true_slope_deg"]) + rng.normal(0, 5)])
    analyze(tmp, os.path.join(tmp, "FAKE_responses.csv"))

if __name__ == "__main__":
    a = sys.argv[1:]
    if a and a[0] == "make":
        dem = None; cell = 1.0
        if "--dem" in a: dem = np.load(a[a.index("--dem") + 1]); cell = float(a[a.index("--cell") + 1]) if "--cell" in a else 1.0
        make(a[1], dem, cell)
    elif a and a[0] == "analyze": analyze(a[1], a[2])
    elif a and a[0] == "selftest": selftest(a[1])
    else: print(__doc__)
